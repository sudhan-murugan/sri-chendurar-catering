// Generates supabase/seed.sql from lib/seed.ts (single source of sample data).
// Run: npm run seed:sql
import { writeFileSync } from "node:fs";
import { buildSeed } from "../lib/seed.ts";

const UID = "__UID__";
const rows = await buildSeed(UID, "__NOW__", (k) => `__ID__${k}`);

function lit(v: unknown): string {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  const s = String(v);
  if (s === UID) return "uid";
  if (s === "__NOW__") return "now()";
  if (s.startsWith("__ID__")) return `pg_temp.sid(uid, '${s.slice(6).replace(/'/g, "''")}')`;
  return `'${s.replace(/'/g, "''")}'`;
}

const stmts = rows.map(({ table, row }) => {
  const cols = ["user_id", ...Object.keys(row)];
  const vals = ["uid", ...Object.values(row).map(lit)];
  return `  insert into public.${table} (${cols.join(", ")}) values (${vals.join(", ")}) on conflict (id) do nothing;`;
});

const sql = `-- Sample data for Sri Chendurar Catering (GENERATED by scripts/gen-seed-sql.ts – do not edit).
-- The app seeds this automatically on first login, so you normally do NOT need to run it.
-- To run manually: Supabase → SQL Editor → paste → Run. It seeds the FIRST user in auth.users.
-- IDs are deterministic, so running it again (or after the app seeded) creates no duplicates.

create or replace function pg_temp.sid(u uuid, k text) returns uuid language sql immutable as $$
  select encode(substring(sha256(convert_to(u::text || ':' || k, 'UTF8')) from 1 for 16), 'hex')::uuid
$$;

do $$
declare uid uuid := (select id from auth.users order by created_at limit 1);
begin
  if uid is null then raise exception 'Create your login user first (Authentication → Users → Add user)'; end if;
${stmts.join("\n")}
end $$;
`;
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`seed.sql written: ${rows.length} rows`);
