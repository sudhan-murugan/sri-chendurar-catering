// Generates out/sw.js after `next build` (static export).
// Precaches every exported file so the whole app – including the calculator
// and shopping list – opens in airplane mode. Version = hash of all files, so
// a new deploy installs a fresh cache and the app shows "புதிய பதிப்பு தயார்".
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const OUT = "out";
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else files.push(p);
  }
})(OUT);

const hash = createHash("sha256");
const urls = [];
for (const f of files.sort()) {
  const rel = relative(OUT, f).split(sep).join("/");
  if (rel === "sw.js" || rel === "_headers" || rel.endsWith(".map") || rel === "404.html" || rel.startsWith("_not-found") || rel === "icons/icon.svg") continue;
  hash.update(rel).update(readFileSync(f));
  // pages are served at their folder URL (trailingSlash: true)
  urls.push("/" + rel.replace(/(^|\/)index\.html$/, "$1"));
}
const version = hash.digest("hex").slice(0, 12);

const sw = `// GENERATED by scripts/build-sw.mjs – do not edit
const VERSION = "scc-${version}";
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(VERSION).then((c) => c.addAll(PRECACHE.map((u) => new Request(u, { cache: "reload" })))));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== VERSION).map((k) => caches.delete(k)))).then(() => self.clients.claim())
  );
});

self.addEventListener("message", (e) => {
  if (e.data === "SKIP_WAITING") self.skipWaiting();
});

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // Supabase API etc. go straight to network

  if (req.mode === "navigate") {
    let path = url.pathname;
    if (!path.endsWith("/") && !path.includes(".")) path += "/";
    e.respondWith(
      caches.match(path, { ignoreSearch: true }).then((hit) => hit || fetch(req).catch(() => caches.match("/")))
    );
    return;
  }

  // static assets & RSC payloads (?_rsc=…): cache first, then network (and remember it)
  e.respondWith(
    caches.match(req, { ignoreSearch: true }).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok && res.type === "basic") {
            const copy = res.clone();
            caches.open(VERSION).then((c) => c.put(req, copy));
          }
          return res;
        })
    )
  );
});
`;
writeFileSync(join(OUT, "sw.js"), sw);

// Response headers for Cloudflare Pages / Netlify (`_headers` file format).
// vercel.json carries the same rules for Vercel. Keep the two in sync.
const SECURITY = [
  "X-Content-Type-Options: nosniff",
  "Referrer-Policy: strict-origin-when-cross-origin",
  "X-Frame-Options: DENY",
  "Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=()",
];
const headers = [
  "/*",
  ...SECURITY.map((h) => "  " + h),
  "/sw.js",
  "  Cache-Control: no-cache",
  "/_next/static/*",
  "  Cache-Control: public, max-age=31536000, immutable",
  "",
].join("\n");
writeFileSync(join(OUT, "_headers"), headers);
console.log(`sw.js: ${urls.length} files precached, version ${version}`);
